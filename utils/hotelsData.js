// Returns static fallback hotels for a city and category
export function getFallbackHotels(city, tourType) {
  // Normalize city name
  const matchedCity = Object.keys(HOTELS_CATALOG).find(c => c.toLowerCase() === city.toLowerCase());
  const cityData = matchedCity ? HOTELS_CATALOG[matchedCity] : HOTELS_CATALOG["default"];
  
  // Normalize vibe type (Fun, Romantic, Adventure)
  let vibeKey = "Adventure";
  if (tourType) {
    if (tourType.toLowerCase().includes("fun")) vibeKey = "Fun";
    else if (tourType.toLowerCase().includes("romantic") || tourType.toLowerCase().includes("romance")) vibeKey = "Romantic";
    else if (tourType.toLowerCase().includes("adventure")) vibeKey = "Adventure";
  }

  // Return the hotels list
  const hotels = cityData[vibeKey] || HOTELS_CATALOG["default"][vibeKey];
  return hotels;
}
